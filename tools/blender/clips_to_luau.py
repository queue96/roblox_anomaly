"""Clip data from build_anims.export_clip_data (json) -> src/shared/HumanClipData.luau: ready-made Bone.Transform keys
for clips the game plays itself on the bones (shared/HumanEmotes), so they need no animation upload.

Same conversion as tools/studio/HumanAnimImport.luau (H.convert):
    T = Rrbx^-1 * C * (B * q * B^-1) * C^-1 * Rrbx,   offset = Rrbx^-1 * (C * B) * t
Rrbx (each Roblox bone's rest frame relative to the RootPart) is measured once in Studio from
ServerStorage.HumanTemplates.human_base and kept in tools/studio/human_base_rbx_rest.json (re-measure after a new
rig import: see HumanAnimImport.restFrames).

    python tools/blender/clips_to_luau.py <anims.json> [out.luau]
Clips written: EMOTES (whole body) + walk (hips and legs only, for the parade dancers' legs)
+ carry_gallon_r (right arm only, the player holding the jerry can).
"""
import json, os, sys


# tiny 3x3 / vector helpers (no numpy here)
def mm(a, b): return [[sum(a[i][k]*b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
def mT(a): return [[a[j][i] for j in range(3)] for i in range(3)]
def mv(a, v): return [sum(a[i][k]*v[k] for k in range(3)) for i in range(3)]
def sub(a, b): return [a[i] - b[i] for i in range(3)]
def dot(a, b): return sum(a[i]*b[i] for i in range(3))
def norm(a): n = dot(a, a) ** 0.5; return [x/n for x in a]
def cross(a, b): return [a[1]*b[2] - a[2]*b[1], a[2]*b[0] - a[0]*b[2], a[0]*b[1] - a[1]*b[0]]

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REST_RBX = os.path.join(ROOT, "tools", "studio", "human_base_rbx_rest.json")
OUT = os.path.join(ROOT, "src", "shared", "HumanClipData.luau")
EMOTES = ["laugh", "cheer", "startle", "sad", "angry", "hurt_lying", "dead_lying"]
ONCE = {"startle"}
RIGHT_ARM = ["shoulder.R", "upper_arm.R", "forearm.R", "hand.R"] + [f"{f}_0{i}.R" for f in ("index", "middle", "ring", "pinky", "thumb") for i in (1, 2, 3)]
SUBSETS = {"walk": ["hips", "thigh.L", "shin.L", "foot.L", "toe.L", "thigh.R", "shin.R", "foot.R", "toe.R"],
           "carry_gallon_r": RIGHT_ARM,   # held jerry can, right hand (client/HumanEmotesRunner HOLD_CLIPS)
           "hold_tray_r": RIGHT_ARM}      # sweets on a leaf on the open right palm


def qmat(x, y, z, w):
    n = (x*x + y*y + z*z + w*w) ** 0.5
    x, y, z, w = x/n, y/n, z/n, w/n
    return [[1 - 2*(y*y + z*z), 2*(x*y - z*w), 2*(x*z + y*w)],
            [2*(x*y + z*w), 1 - 2*(x*x + z*z), 2*(y*z - x*w)],
            [2*(x*z - y*w), 2*(y*z + x*w), 1 - 2*(x*x + y*y)]]


def mquat(m):
    t = m[0][0] + m[1][1] + m[2][2]
    if t > 0:
        s = (t + 1.0) ** 0.5 * 2
        w, x, y, z = 0.25*s, (m[2][1] - m[1][2])/s, (m[0][2] - m[2][0])/s, (m[1][0] - m[0][1])/s
    elif m[0][0] > m[1][1] and m[0][0] > m[2][2]:
        s = (1.0 + m[0][0] - m[1][1] - m[2][2]) ** 0.5 * 2
        w, x, y, z = (m[2][1] - m[1][2])/s, 0.25*s, (m[0][1] + m[1][0])/s, (m[0][2] + m[2][0])/s
    elif m[1][1] > m[2][2]:
        s = (1.0 + m[1][1] - m[0][0] - m[2][2]) ** 0.5 * 2
        w, x, y, z = (m[0][2] - m[2][0])/s, (m[0][1] + m[1][0])/s, 0.25*s, (m[1][2] + m[2][1])/s
    else:
        s = (1.0 + m[2][2] - m[0][0] - m[1][1]) ** 0.5 * 2
        w, x, y, z = (m[1][0] - m[0][1])/s, (m[0][2] + m[2][0])/s, (m[1][2] + m[2][1])/s, 0.25*s
    if w < 0:
        x, y, z, w = -x, -y, -z, -w
    return x, y, z, w


def frame(up, side):
    y = norm(up)
    x = norm(sub(side, [c*dot(side, y) for c in y]))
    z = cross(x, y)
    return [[x[i], y[i], z[i]] for i in range(3)]


def main(src, out=OUT):
    d = json.load(open(src))
    rbx = json.load(open(REST_RBX))
    rest = d["rest"]
    R = {n: [v[3:6], v[6:9], v[9:12]] for n, v in rbx.items()}
    P = {n: v[0:3] for n, v in rbx.items()}
    bp = {n: v[4:7] for n, v in rest.items()}
    C = mm(frame(sub(P["head"], P["hips"]), sub(P["thigh.L"], P["thigh.R"])), mT(frame(sub(bp["head"], bp["hips"]), sub(bp["thigh.L"], bp["thigh.R"]))))

    def convert(key, rq, Rr):
        B = qmat(*rq[:4])
        rot = mm(mm(mm(mT(Rr), C), mm(mm(B, qmat(*key[:4])), mT(B))), mm(mT(C), Rr))
        t = mv(mT(Rr), mv(mm(C, B), key[4:7]))
        return [round(float(v), 3) for v in t] + [round(float(v), 4) for v in mquat(rot)]

    lines = ["--!strict",
             "-- GENERATED by tools/blender/clips_to_luau.py from build_anims.py clip data - do not edit by hand.",
             "-- Bone.Transform keys (x, y, z, qx, qy, qz, qw) per bone, for shared/HumanEmotes. A track with one key = held still.",
             "return {"]
    for name in EMOTES + list(SUBSETS):
        clip = d["clips"].get(name)
        if not clip:
            print("missing clip", name); continue
        keep = SUBSETS.get(name)
        lines.append(f'\t["{name}"] = {{ length = {clip["length"]:.4f}, once = {"true" if name in ONCE else "false"},')
        lines.append("\t\ttimes = { " + ", ".join(f"{t:g}" for t in clip["times"]) + " },")
        lines.append("\t\ttracks = {")
        for bone, keys in clip["tracks"].items():
            if bone not in R or (keep and bone not in keep):
                continue
            ks = [convert(k, rest[bone], R[bone]) for k in keys]
            if all(k == ks[0] for k in ks):
                ks = ks[:1]
            lines.append(f'\t\t\t["{bone}"] = {{ ' + ", ".join("{" + ", ".join(f"{v:g}" for v in k) + "}" for k in ks) + " },")
        lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main(sys.argv[1], *(sys.argv[2:3]))
