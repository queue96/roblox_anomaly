"""ท่าประกอบคำพูดแบบครึ่งตัวบนสำหรับคนนั่งรถ (2026-11-09) -> src/shared/SeatGestureData.luau

ท่า mocap (assets/models/mocap/out/human_base_mocap_anims.json จาก mocap_retarget.py) เป็นท่ายืนทั้งตัว:
ใส่เป็น animation ทับคนนั่งรถแล้วลำตัวจะตั้งตรง ขายืด -> เอาเฉพาะ "การขยับ" ของลำตัว/คอ/หัว/ไหล่ เทียบเฟรมแรก
(delta ในพิกัด Bone.Transform ของ Roblox) แล้ว client/HumanEmotesRunner คูณทับท่านั่งที่เล่นอยู่ (ไม่ต้องอัปโหลด)

    python tools/blender/seat_gestures_to_luau.py [anims.json]
แปลงแกนกระดูกแบบเดียวกับ clips_to_luau.py (ท่าพักของ rig Roblox: tools/studio/human_base_rbx_rest.json)
"""
import importlib.util, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("clips_to_luau", os.path.join(HERE, "clips_to_luau.py"))
C2L = importlib.util.module_from_spec(spec)
spec.loader.exec_module(C2L)

ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, "assets", "models", "mocap", "out", "human_base_mocap_anims.json")
OUT = os.path.join(ROOT, "src", "shared", "SeatGestureData.luau")
CLIPS = {"talk": 1.0, "talk_2": 1.0, "nod_yes": 1.0, "shake_no": 1.0, "shrug": 1.0}   # ชื่อ -> ตัวคูณความแรง
BONES = ["spine", "chest", "neck", "head", "shoulder.L", "shoulder.R"]


def qmul(a, b):
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return (aw * bx + ax * bw + ay * bz - az * by,
            aw * by - ax * bz + ay * bw + az * bx,
            aw * bz + ax * by - ay * bx + az * bw,
            aw * bw - ax * bx - ay * by - az * bz)


def qinv(q):
    return (-q[0], -q[1], -q[2], q[3])


def main(src=SRC, out=OUT):
    d = json.load(open(src))
    rbx = json.load(open(C2L.REST_RBX))
    rest = d["rest"]
    R = {n: [v[3:6], v[6:9], v[9:12]] for n, v in rbx.items()}
    P = {n: v[0:3] for n, v in rbx.items()}
    bp = {n: v[4:7] for n, v in rest.items()}
    Cm = C2L.mm(C2L.frame(C2L.sub(P["head"], P["hips"]), C2L.sub(P["thigh.L"], P["thigh.R"])),
                C2L.mT(C2L.frame(C2L.sub(bp["head"], bp["hips"]), C2L.sub(bp["thigh.L"], bp["thigh.R"]))))

    def rot(key, rq, Rr):
        B = C2L.qmat(*rq[:4])
        m = C2L.mm(C2L.mm(C2L.mm(C2L.mT(Rr), Cm), C2L.mm(C2L.mm(B, C2L.qmat(*key[:4])), C2L.mT(B))), C2L.mm(C2L.mT(Cm), Rr))
        return C2L.mquat(m)

    lines = ["--!strict",
             "-- GENERATED by tools/blender/seat_gestures_to_luau.py - do not edit by hand.",
             "-- ท่าประกอบคำพูดของคนนั่งรถ: การหมุนของกระดูกเทียบเฟรมแรก (qx, qy, qz, qw ในแกน Bone.Transform)",
             "-- client/HumanEmotesRunner: Transform = ท่าฐาน * delta (ผสมเข้า/ออกนุ่มๆ)",
             "return {"]
    for name, gain in CLIPS.items():
        clip = d["clips"].get(name)
        if not clip:
            print("missing", name)
            continue
        lines.append(f'\t["{name}"] = {{ length = {clip["length"]:.4f},')
        lines.append("\t\ttimes = { " + ", ".join(f"{t:g}" for t in clip["times"]) + " },")
        lines.append("\t\ttracks = {")
        for bone in BONES:
            keys = clip["tracks"].get(bone)
            if not keys or bone not in R:
                continue
            qs = [rot(k, rest[bone], R[bone]) for k in keys]
            q0i = qinv(qs[0])
            ds = []
            for q in qs:
                dq = qmul(q0i, q)
                if dq[3] < 0:
                    dq = tuple(-x for x in dq)
                ds.append(dq)
            if all(abs(x - y) < 1e-4 for dq in ds for x, y in zip(dq, ds[0])):
                continue
            lines.append(f'\t\t\t["{bone}"] = {{ ' + ", ".join("{" + ", ".join(f"{round(v, 4):g}" for v in dq) + "}" for dq in ds) + " },")
        lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main(*(sys.argv[1:2] or [SRC]))
